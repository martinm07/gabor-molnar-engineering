const nodeUUIDs = new WeakMap();

function getNodeUUID(node: Node) {
  // Check if we already have a UUID for this node
  let uuid = nodeUUIDs.get(node);

  if (!uuid) {
    // Generate a new UUID
    uuid = crypto.randomUUID();
    // Store the mapping
    nodeUUIDs.set(node, uuid);
  }

  return uuid;
}

