function processMutations(mutations: MutationRecord[]): TempMutationRecord[] {
  // TODO: Consider that previousSibling may not actually be the previous sibling
  //        for all of the nodes in a list of addedNodes or removedNodes (rather, they
  //        are siblings of each other).
  const final: TempMutationRecord[] = mutations.flatMap((record) => {
    const total =
      record.type === "childList"
        ? record.addedNodes.length + record.removedNodes.length
        : 1;
    const added = record.type === "childList" ? record.addedNodes.length : NaN;
    return Array.from(Array(total), (_, i) => {
      return {
        target: record.target,
        type: record.type,
        attributeName: record.attributeName,
        oldValue: record.oldValue,
        addedNode: i < added ? record.addedNodes[i] : null,
        removedNode: i >= added ? record.removedNodes[i] : null,
        previousSibling: record.previousSibling,
      };
    });
  });

  // number should be negative if a is before b
  final.sort((a, b) => {
    // if (a.addedNode === b.removedNode && a.addedNode?.isConnected) return 1;
    // else if (a.removedNode === b.addedNode && b.addedNode?.isConnected) return -1;
    // else if (a.addedNode === b.removedNode && b.addedNode?.isConnected) return 1;
    // else if (a.removedNode === b.addedNode && b.addedNode?.isConnected) return -1;
    // a.addedNode?.compareDocumentPosition(b.removedNode!)
    const aa = a.addedNode;
    const ar = a.removedNode;
    const ba = b.addedNode;
    const br = b.removedNode;

    // // For one node to be a child of the other, they have to either both
    // //  be connected to the DOM or both be disconnected.
    // const isAffecting = (a: Node, b: Node) =>
    //   a === b ||
    //   a.compareDocumentPosition(b) &
    //     (Node.DOCUMENT_POSITION_CONTAINED_BY | Node.DOCUMENT_POSITION_CONTAINS);

    // // Handling the order between add and remove calls
    // if (aa !== null && br !== null && isAffecting(aa, br)) {
    //   if (aa.isConnected) return 1;
    //   else return -1;
    // } else if (ba !== null && ar !== null && isAffecting(ba, ar)) {
    //   if (ba.isConnected) return -1;
    //   else return 1;
    // }

    // Handling the order between add calls
    if (aa !== null && ba !== null) {
      const compare = aa.compareDocumentPosition(ba);
      // Means B is contained by A
      if (compare & Node.DOCUMENT_POSITION_CONTAINED_BY) return -1;
      // Means B contains A
      else if (compare & Node.DOCUMENT_POSITION_CONTAINS) return 1;
      else return 0;
    }

    // The order between remove calls shouldn't matter- the reason the order
    //  between add calls matters is that finding the index of a child node
    //  will require knowing the other siblings and parents' indexes

    if (ar !== null && br !== null) {
      const compare = ar.compareDocumentPosition(br);
      if (compare & Node.DOCUMENT_POSITION_CONTAINED_BY) return -1;
      else if (compare & Node.DOCUMENT_POSITION_CONTAINS) return 1;
      else return 0;
    }

    // --------------------
    if (aa !== null && br !== null) return 1;
    else if (ar !== null && ba !== null) return -1;

    return 0;
  });
  return final;
}

export function patchMutations(
  mutations: MutationRecord[],
  docNodes: DocNodeMap,
  containerEl: Element,
  documentID: number,
  opts: {
    updateHTMLStr?: string;
    debug?: boolean;
    useIgnoreAddedNodeMutations?: boolean;
  } = {},
) {
  const totalAdded: Node[] | undefined = opts.useIgnoreAddedNodeMutations
    ? []
    : undefined;
  let newHTMLStr: string = opts.updateHTMLStr ?? "";
  // if (opts.debug && opts.updateHTMLStr !== undefined) {
  //   console.log("%cOriginal HTML string", "font-size: x-large; color: yellow");
  //   console.log(opts.updateHTMLStr);
  // }

  const patches: DocPatch[] = [];
  // We want mutations which are removing nodes to be done before those which are adding
  //  nodes. This is for the case where a node is being moved from one place into another.
  //  To the mutation observer, this looks like adding a node to the new container and removing
  //  the same node from the old container. If this is received as first adding, then removing,
  //  it will mess up handleMutationRecordPatch, which will first not add the node (because
  //  it's already in docNodes) and then remove it.
  // mutations.sort((a, b) => {
  //   // If either a or b have both an addedNodes list and removedNodes list, then
  //   //  we don't care about sorting them
  //   // (The only way to get both an addedNodes list and removedNodes list on the same record
  //   //  is assigning a HTML string. That involves removing the nodes- not moving them- before
  //   //  adding entirely new nodes- not moving existing nodes; thus these records aren't a concern)
  //   if (
  //     (a.removedNodes.length > 0 && a.addedNodes.length > 0) ||
  //     (b.removedNodes.length > 0 && b.addedNodes.length > 0)
  //   )
  //     return 0;
  //   // number should be negative if a is before b
  //   if (a.removedNodes.length > 0 && b.addedNodes.length > 0) return -1;
  //   if (a.addedNodes.length > 0 && b.removedNodes.length > 0) return 1;
  //   return 0;
  // });

  const processedMutations = processMutations(mutations);
  console.log("Processed mutations:", processedMutations);
  for (const mutation of processedMutations) {
    // Change code if you want startIndexLog, attributeChange and/or characterDataChange
    // Note, for attributeChange requires "attributeOldValue: true" in observer options, and
    //           characterDataChange requires "characterDataOldValue: true" in observer options.
    const newPatches = handleMutationRecordPatch(
      mutation,
      docNodes,
      containerEl,
      totalAdded,
      {
        htmlStr:
          opts.debug && opts.updateHTMLStr !== undefined
            ? newHTMLStr
            : undefined,
        startIndexLog: opts.debug ? true : false,
        attributeChange: opts.debug ? false : false,
        characterDataChange: opts.debug ? false : false,
      },
    );

    // if (totalAdded) totalAdded.push(...mutation.addedNodes);
    if (totalAdded && mutation.addedNode) totalAdded.push(mutation.addedNode);

    if (opts.updateHTMLStr !== undefined)
      newHTMLStr = applyPatches(newHTMLStr, newPatches);
    if (opts.debug) {
      // console.log(newPatches);
      // if (opts.updateHTMLStr !== undefined) console.log(newHTMLStr);
    }
    patches.push(...newPatches);
  }

  const createFetch = () =>
    fetch_("/documents/sync_document_patch", {
      method: "post",
      body: JSON.stringify({
        id: documentID,
        patches: patches.map((patch) => {
          return {
            index: patch.start,
            length: patch.length,
            value: patch.value,
          };
        }),
      }),
    });
  if (patches.length > 0) {
    if (prevFetch === null) prevFetch = createFetch();
    else prevFetch = prevFetch.then(createFetch);
  }

  if (opts.debug) {
    console.log("💜💜💜 Patch sync");
    console.log(patches);
    console.log(docNodes);
    if (opts.updateHTMLStr !== undefined && patches.length > 0)
      console.log(newHTMLStr);
    console.log("\n------------------------\n");
  }

  return opts.updateHTMLStr ? newHTMLStr : "";
}
